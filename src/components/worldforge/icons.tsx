export function getIcon(name: string): LucideIcon {
  return iconMap[name] ?? Boxes;
}

/** Renders a category icon by name. Avoids creating components during render. */
export function CategoryIcon({
  name,
  className,
}: {
  name: string;
  className?: string;
}) {
  const Icon = iconMap[name] ?? Boxes;
  return <Icon className={className} />;
}
